# №1755. Представим каждый досмотр интервалом [начало, конец).
# Аппарат, освободившийся ровно в момент прибытия, уже может принять новый груз.
# busy хранит времена окончания только текущих досмотров. Его длина — число занятых аппаратов.

# Подключаем sys для чтения входных данных и вывода результата.
import sys
# Подключаем готовые операции минимальной кучи.
import heapq

# Читаем весь ввод, делим по пробелам и переносам строк, превращаем части в целые числа и собираем список.
data = list(map(int, sys.stdin.buffer.read().split()))
# Срезы с шагом 2 берут прибытия и длительности; zip соединяет их в пары, sorted сортирует пары по прибытию.
jobs = sorted(zip(data[1::2], data[2::2]))
# Пустая минимальная куча моментов окончания досмотров.
busy = []
# Максимальное число одновременно занятых аппаратов; для отсутствующих грузов останется 0.
answer = 0
# Берём очередную пару, распаковывая прибытие и длительность в две переменные.
for start, duration in jobs:
    # Пока есть досмотры, завершившиеся к прибытию груза; busy защищает от обращения к пустому списку.
    while busy and busy[0] <= start:
        # Удаляем самое раннее окончание: этот аппарат уже свободен.
        heapq.heappop(busy)
    # Начинаем новый досмотр и сохраняем время его завершения.
    heapq.heappush(busy, start + duration)
    # Обновляем рекорд одновременной занятости; именно столько аппаратов обязательно понадобится.
    answer = max(answer, len(busy))
# Выводим минимально необходимое число аппаратов.
print(answer)

