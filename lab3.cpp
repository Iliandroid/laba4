// №3493. Минимальная куча: родитель не больше детей, минимум находится в heap[0].
// vector хранит элементы, но операции кучи мы выполняем сами.
// Индексы начинаются с 0. Дети позиции i: 2*i+1 и 2*i+2, родитель: (i-1)/2.
// std:: означает имя из стандартной библиотеки C++. Точка с запятой завершает инструкцию.

// Подключаем средства ввода cin и вывода cout.
#include <iostream>
// Подключаем строковый тип string для названий команд.
#include <string>
// Подключаем динамический массив vector для хранения кучи.
#include <vector>

// Точка входа: выполнение программы начинается здесь; фигурные скобки ограничивают блок.
int main() {
    // Отключаем синхронизацию с вводом C для ускорения чтения.
    std::ios::sync_with_stdio(false);
    // Отключаем автоматическую очистку буфера вывода перед чтением; для этой задачи она не нужна.
    std::cin.tie(nullptr);
    // Создаём пустой массив целых long long — обычно 64-битных чисел.
    std::vector<long long> heap;
    // Переменная для названия очередной команды.
    std::string command;
    // Читаем слово и повторяем цикл, пока чтение успешно; число команд заранее не задано.
    while (std::cin >> command) {
        // Выбираем ветку очистки; == сравнивает значения.
        if (command == "CLEAR") {
            // Удаляем все элементы массива.
            heap.clear();
        // Если команда ADD, нужно добавить число.
        } else if (command == "ADD") {
            // Объявляем переменную для добавляемого числа.
            long long x;
            // Считываем аргумент команды ADD.
            std::cin >> x;
            // Добавляем число в конец массива.
            heap.push_back(x);
            // Индекс нового элемента; size_t — беззнаковый тип для размеров и индексов.
            std::size_t i = heap.size() - 1;
            // Пока есть родитель и он больше x, поднимаемся; && означает «и» и проверяет части слева направо.
            while (i > 0 && heap[(i - 1) / 2] > x) {
                // Находим индекс родителя; деление целых отбрасывает дробную часть.
                std::size_t p = (i - 1) / 2;
                // Сдвигаем большего родителя вниз, освобождая место выше.
                heap[i] = heap[p];
                // Продолжаем подъём с позиции родителя.
                i = p;
            }
            // Записываем сохранённое число на найденное место.
            heap[i] = x;
        // Ветка удаления и вывода минимума.
        } else if (command == "EXTRACT") {
            // Проверяем, пуста ли куча.
            if (heap.empty()) {
                // Если извлекать нечего, выводим CANNOT и перевод строки.
                std::cout << "CANNOT\n";
                // Переходим к следующей команде, не выполняя оставшуюся часть цикла.
                continue;
            }
            // Корень — минимальное число; выводим его и перевод строки.
            std::cout << heap[0] << '\n';
            // Сохраняем последний элемент, которым заменим удаляемый корень.
            long long x = heap.back();
            // Удаляем последний элемент из массива.
            heap.pop_back();
            // Если элемент был единственным, куча теперь пуста и восстанавливать её не нужно.
            if (heap.empty()) continue;
            // Начинаем поиск места для x с корня.
            std::size_t i = 0;
            // Спускаемся, пока у текущей позиции существует левый ребёнок.
            while (2 * i + 1 < heap.size()) {
                // Первым кандидатом выбираем левого ребёнка.
                std::size_t j = 2 * i + 1;
                // Если правый ребёнок существует и меньше левого, выбираем его; ++j увеличивает индекс на 1.
                if (j + 1 < heap.size() && heap[j + 1] < heap[j]) ++j;
                // Если меньший ребёнок не меньше x, место найдено; break завершает цикл спуска.
                if (heap[j] >= x) break;
                // Поднимаем меньшего ребёнка на освободившееся место.
                heap[i] = heap[j];
                // Продолжаем спуск с позиции выбранного ребёнка.
                i = j;
            }
            // Записываем сохранённое число на найденное место.
            heap[i] = x;
        }
    }
}

