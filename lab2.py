# №754. Heapsort: строим максимальную кучу и по одному переносим максимумы в конец.
# size — длина активной части кучи; элементы начиная с size уже не трогаем.
# Просеивание восстанавливает порядок, если поддеревья детей уже являются кучами.

# Подключаем sys для чтения входных данных и вывода результата.
import sys

# Функция просеивания: a — список, i — начальная позиция, size — размер активной кучи.
def sift(a, i, size):
    # Запоминаем перемещаемое значение, чтобы не потерять его при сдвигах.
    x = a[i]
    # Пока левый ребёнок находится внутри активной кучи, можно спускаться.
    while 2 * i + 1 < size:
        # Сначала выбираем левого ребёнка.
        j = 2 * i + 1
        # Выбираем большего ребёнка, проверив, что правый существует.
        if j + 1 < size and a[j + 1] > a[j]:
            # Переходим к правому ребёнку; это сокращение для j = j + 1.
            j += 1
        # Если больший ребёнок не больше x, порядок кучи уже соблюдается.
        if a[j] <= x:
            # Немедленно завершаем ближайший цикл.
            break
        # Переносим большего ребёнка вверх.
        a[i] = a[j]
        # Продолжаем спуск с позиции выбранного ребёнка.
        i = j
    # Ставим сохранённое значение на окончательную позицию.
    a[i] = x

# Объявляем функцию с основной частью программы; код внутри выделен отступом.
def main():
    # Читаем весь ввод, делим по пробелам и переносам строк, превращаем части в целые числа и собираем список.
    data = list(map(int, sys.stdin.buffer.read().split()))
    # Первое введённое число — количество элементов массива.
    n = data[0]
    # Срез [1:] берёт все элементы начиная со второго; это числа для сортировки.
    a = data[1:]
    # Идём от последнего родителя к корню включительно; последний -1 задаёт шаг назад.
    for i in range(n // 2 - 1, -1, -1):
        # Восстанавливаем кучу с корнем i; дети уже обработаны на предыдущих шагах.
        sift(a, i, n)
    # Последовательно уменьшаем конец активной части от n-1 до 1.
    for end in range(n - 1, 0, -1):
        # Обмениваем максимум в корне с последним активным элементом; максимум занял окончательное место.
        a[0], a[end] = a[end], a[0]
        # Восстанавливаем кучу только в позициях от 0 до end-1.
        sift(a, 0, end)
    # Звёздочка передаёт элементы как отдельные аргументы print, поэтому они выводятся через пробел.
    print(*a)

# Запускаем main только при непосредственном запуске файла, а не при его импорте.
if __name__ == "__main__":
    # Вызываем объявленную выше основную функцию.
    main()

