# №755. Максимальная куча: самое большое число всегда находится в heap[0].
# Куча — список, который мысленно изображаем деревом. Это не полностью отсортированный список.
# Для позиции i: родитель (i-1)//2, левый ребёнок 2*i+1, правый 2*i+2.
# При перемещении мы сдвигаем соседние значения, а x записываем только на окончательное место.

# Подключаем sys для чтения входных данных и вывода результата.
import sys

# Объявляем функцию с основной частью программы; код внутри выделен отступом.
def main():
    # read читает весь ввод, split делит по пробелам/переносам, map(int, ...) превращает части в числа; iter позволяет брать их по одному.
    data = iter(map(int, sys.stdin.buffer.read().split()))
    # Берём первое число — количество команд. next продвигает итератор к следующему элементу.
    n = next(data)
    # Создаём пустой список для элементов кучи.
    heap = []
    # Накапливаем текстовые ответы, чтобы затем вывести их одним действием.
    out = []
    # Повторяем обработку n раз; номер повтора не нужен, поэтому переменную называем _.
    for _ in range(n):
        # Берём код команды: 0 означает добавление.
        if next(data) == 0:
            # Берём число, которое нужно добавить.
            x = next(data)
            # Добавляем число в конец списка; порядок кучи пока может нарушиться.
            heap.append(x)
            # Индекс последнего элемента: длина минус один, поскольку нумерация начинается с нуля.
            i = len(heap) - 1
            # Пока мы не у корня (i != 0) и родитель меньше x, поднимаемся. // — целочисленное деление.
            while i and heap[(i - 1) // 2] < x:
                # Вычисляем индекс родителя текущей позиции.
                p = (i - 1) // 2
                # Сдвигаем родителя вниз, освобождая место для x выше.
                heap[i] = heap[p]
                # Продолжаем поиск места с позиции родителя.
                i = p
            # Записываем сохранённое число на найденное место.
            heap[i] = x
        # Вторая ветка: при корректном вводе здесь выполняется команда извлечения.
        else:
            # Корень содержит максимум; превращаем его в строку и сохраняем ответ.
            out.append(str(heap[0]))
            # Удаляем и сохраняем последний элемент; им заменим извлечённый корень.
            x = heap.pop()
            # Если после удаления список непустой, нужно восстановить кучу.
            if heap:
                # Начинаем с корня — позиции 0.
                i = 0
                # Продолжаем, пока у текущей позиции есть хотя бы левый ребёнок.
                while 2 * i + 1 < len(heap):
                    # Сначала выбираем левого ребёнка.
                    j = 2 * i + 1
                    # Если правый ребёнок существует и больше левого, лучше выбрать его.
                    if j + 1 < len(heap) and heap[j + 1] > heap[j]:
                        # Переходим к правому ребёнку; это сокращение для j = j + 1.
                        j += 1
                    # Если даже больший ребёнок не больше x, подходящее место уже найдено.
                    if heap[j] <= x:
                        # Немедленно завершаем ближайший цикл.
                        break
                    # Поднимаем выбранного ребёнка на освободившуюся позицию.
                    heap[i] = heap[j]
                    # Продолжаем спуск с позиции выбранного ребёнка.
                    i = j
                # Записываем сохранённое число на найденное место.
                heap[i] = x
    # Объединяем ответы символом новой строки и выводим их.
    print("\n".join(out))

# Запускаем main только при непосредственном запуске файла, а не при его импорте.
if __name__ == "__main__":
    # Вызываем объявленную выше основную функцию.
    main()

