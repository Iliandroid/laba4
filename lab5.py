# №746. Чтобы заплатить меньше, каждый раз складываем два наименьших доступных числа.
# Например: 10+11=21, 12+13=25, 21+25=46. Стоимость: (21+25+46)*5 центов.
# heapq поддерживает минимальную кучу: в позиции 0 всегда наименьший элемент.

# Подключаем sys для чтения входных данных и вывода результата.
import sys
# Подключаем готовые операции минимальной кучи.
import heapq

# Читаем весь ввод, делим по пробелам и переносам строк, превращаем части в целые числа и собираем список.
data = list(map(int, sys.stdin.buffer.read().split()))
# Первое число — N; остальные числа копируем в список будущей кучи.
heap = data[1:]
# Перестраиваем список в минимальную кучу за линейное время.
heapq.heapify(heap)
# Сумма всех промежуточных результатов сложений; это ещё не денежная стоимость.
total = 0
# Пока осталось хотя бы два числа, выполняем очередное сложение.
while len(heap) > 1:
    # Дважды удаляем текущий минимум и складываем извлечённые числа.
    value = heapq.heappop(heap) + heapq.heappop(heap)
    # Прибавляем очередной результат к общей сумме результатов.
    total += value
    # Возвращаем результат в кучу: он может участвовать в следующих сложениях.
    heapq.heappush(heap, value)
# 5% от целого числа денежных единиц — это 5 центов за единицу; считаем без дробных ошибок.
cents = total * 5
# // 100 даёт целую денежную часть, % 100 — остаток центов; :02d дополняет центы нулём до двух цифр.
print(f"{cents // 100}.{cents % 100:02d}")

