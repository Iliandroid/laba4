# №3492. heapq умеет быстро извлекать минимум. Для максимума сохраняем числа со знаком минус.
# Например, 10 и 3 хранятся как -10 и -3: минимум -10 после смены знака даёт максимум 10.
# Куча не обязана быть полностью отсортирована: гарантируется минимум в позиции 0.

# Подключаем sys для чтения входных данных и вывода результата.
import sys
# Подключаем готовые операции минимальной кучи.
import heapq

# Создаём пустой список для элементов кучи.
heap = []
# Накапливаем текстовые ответы, чтобы затем вывести их одним действием.
out = []
# Читаем команды построчно до конца ввода. buffer возвращает байты.
for line in sys.stdin.buffer:
    # Делим строку на команду и, если он есть, её аргумент.
    command = line.split()
    # Проверяем, не оказалась ли строка пустой.
    if not command:
        # Пропускаем остаток текущего повтора и переходим к следующей строке.
        continue
    # Сравниваем команду с CLEAR; префикс b нужен для сравнения байтов с байтами.
    if command[0] == b"CLEAR":
        # Удаляем все элементы кучи.
        heap.clear()
    # Если это не CLEAR, проверяем команду добавления ADD.
    elif command[0] == b"ADD":
        # Преобразуем аргумент в число, меняем знак и добавляем с восстановлением кучи.
        heapq.heappush(heap, -int(command[1]))
    # Вторая ветка: при корректном вводе здесь выполняется команда извлечения.
    else:
        # Если куча непустая, удаляем минимум, меняем знак обратно и сохраняем ответ; иначе сохраняем CANNOT.
        out.append(str(-heapq.heappop(heap)) if heap else "CANNOT")
# Выводим накопленные ответы, разделяя их переносами строк.
sys.stdout.write("\n".join(out))

