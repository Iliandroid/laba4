# №3407. Вместо перебора секунд обрабатываем ближайшие рождения рыбок.
# В куче events хранится по одному будущему событию для каждого аквариума.
# Событие — пара (время, индекс). Пары сравниваются сначала по времени, затем по индексу.
# Если два разных аквариума требуют присутствия одновременно, зарегистрировать оба невозможно.

# Подключаем sys для чтения входных данных и вывода результата.
import sys
# Подключаем готовые операции минимальной кучи.
import heapq

# Читаем весь ввод, делим по пробелам и переносам строк, превращаем части в целые числа и собираем список.
data = list(map(int, sys.stdin.buffer.read().split()))
# Убираем первое число n, оставляем численности колоний.
population = data[1:]
# Генератор списка создаёт пары первого рождения и индекса; enumerate даёт индекс i и численность f.
events = [(max(1000 - f, 1), i) for i, f in enumerate(population)]
# Строим кучу событий; ближайшее по времени событие окажется в корне.
heapq.heapify(events)
# Время последнего зарегистрированного рождения; сначала это начальный момент.
time = 0
# Начальная позиция Игоря: первый аквариум имеет индекс 0.
position = 0
# Повторяем обработку событий до первого недостижимого рождения.
while True:
    # Удаляем ближайшее событие и распаковываем его время и индекс аквариума.
    birth, aquarium = heapq.heappop(events)
    # abs даёт расстояние между аквариумами; сравниваем нужное время пути с доступным временем.
    if abs(aquarium - position) > birth - time:
        # Выводим время первого рождения, к которому Игорь не успевает.
        print(birth)
        # Немедленно завершаем ближайший цикл.
        break
    # Успели: фиксируем новое время и позицию. При раннем прибытии можно было подождать.
    time, position = birth, aquarium
    # В этом аквариуме родилась одна рыбка, увеличиваем численность.
    population[aquarium] += 1
    # По новой численности вычисляем задержку, прибавляем к текущему рождению и планируем следующее.
    heapq.heappush(events, (birth + max(1000 - population[aquarium], 1), aquarium))

